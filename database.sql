CREATE OR REPLACE FUNCTION get_freefire_packages()
RETURNS TABLE (
  id TEXT,
  label TEXT,
  diamonds INTEGER,
  supplier_usd NUMERIC,
  usd_ars_rate NUMERIC,
  final_price_ars INTEGER,
  supplier_url TEXT,
  updated_at TIMESTAMPTZ,
  active BOOLEAN,
  stock_available BIGINT
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT package.id, package.label, package.diamonds, package.supplier_usd,
    package.usd_ars_rate, package.final_price_ars, package.supplier_url,
    package.updated_at, package.active,
    COUNT(pin.id) FILTER (WHERE pin.estado = 'disponible') AS stock_available
  FROM freefire_packages AS package
  LEFT JOIN pines AS pin ON pin.paquete_id = package.id
  WHERE package.active
  GROUP BY package.id
  ORDER BY package.diamonds ASC;
$$;

CREATE OR REPLACE FUNCTION refresh_freefire_packages(p_packages JSONB, p_updated_at TIMESTAMPTZ)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE freefire_packages SET active = FALSE
  WHERE id NOT IN (
    SELECT item.id FROM jsonb_to_recordset(p_packages) AS item(id TEXT)
  );

  INSERT INTO freefire_packages
    (id, label, diamonds, supplier_usd, usd_ars_rate, final_price_ars,
     supplier_url, updated_at, active)
  SELECT item.id, item.label, item.diamonds, item.supplier_usd, item.usd_ars_rate,
    item.final_price_ars, item.supplier_url, p_updated_at, TRUE
  FROM jsonb_to_recordset(p_packages) AS item(
    id TEXT, label TEXT, diamonds INTEGER, supplier_usd NUMERIC,
    usd_ars_rate NUMERIC, final_price_ars INTEGER, supplier_url TEXT
  )
  ON CONFLICT (id) DO UPDATE SET
    label = EXCLUDED.label,
    diamonds = EXCLUDED.diamonds,
    supplier_usd = EXCLUDED.supplier_usd,
    usd_ars_rate = EXCLUDED.usd_ars_rate,
    final_price_ars = EXCLUDED.final_price_ars,
    supplier_url = EXCLUDED.supplier_url,
    updated_at = EXCLUDED.updated_at,
    active = TRUE;

  INSERT INTO app_settings (key, value)
  VALUES ('catalog_updated_at', p_updated_at::TEXT)
  ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
END;
$$;

CREATE OR REPLACE FUNCTION get_pin_stock()
RETURNS TABLE (paquete_id TEXT, disponible BIGINT, reservado BIGINT, vendido BIGINT)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT pin.paquete_id,
    COUNT(*) FILTER (WHERE pin.estado = 'disponible') AS disponible,
    COUNT(*) FILTER (WHERE pin.estado = 'reservado') AS reservado,
    COUNT(*) FILTER (WHERE pin.estado = 'vendido') AS vendido
  FROM pines AS pin
  GROUP BY pin.paquete_id
  ORDER BY pin.paquete_id;
$$;

CREATE OR REPLACE FUNCTION claim_order_email(p_order_id TEXT, p_now TIMESTAMPTZ)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  affected_rows INTEGER;
BEGIN
  UPDATE freefire_orders
  SET email_sending_at = p_now
  WHERE id = p_order_id AND email_sent_at IS NULL
    AND (email_sending_at IS NULL OR email_sending_at < p_now - INTERVAL '5 minutes');
  GET DIAGNOSTICS affected_rows = ROW_COUNT;
  RETURN affected_rows = 1;
END;
$$;

CREATE OR REPLACE FUNCTION assign_pin_to_order(
  p_order_id TEXT, p_payment_id TEXT, p_paid_at TIMESTAMPTZ
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  purchase freefire_orders%ROWTYPE;
  selected_pin pines%ROWTYPE;
BEGIN
  SELECT * INTO purchase FROM freefire_orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe la compra asociada al pago.' USING ERRCODE = 'P0002';
  END IF;
  IF purchase.payment_id IS NOT NULL AND purchase.payment_id <> p_payment_id THEN
    RAISE EXCEPTION 'La compra ya está asociada a otro pago.' USING ERRCODE = '23505';
  END IF;

  IF purchase.fulfillment_status = 'assigned' THEN
    SELECT * INTO selected_pin FROM pines
    WHERE order_id = purchase.id AND estado = 'vendido';
    IF NOT FOUND THEN
      RAISE EXCEPTION 'La orden % indica PIN asignado pero no tiene un PIN vendido asociado.', purchase.id;
    END IF;
    IF purchase.payment_id IS NULL THEN
      UPDATE freefire_orders SET payment_id = p_payment_id WHERE id = purchase.id;
      SELECT * INTO purchase FROM freefire_orders WHERE id = purchase.id;
    END IF;
    RETURN jsonb_build_object(
      'status', 'assigned', 'order', to_jsonb(purchase), 'pin', to_jsonb(selected_pin)
    );
  END IF;

  IF purchase.fulfillment_status = 'out_of_stock_pending_refund' THEN
    RETURN jsonb_build_object('status', 'out_of_stock_pending_refund', 'order', to_jsonb(purchase), 'pin', NULL);
  END IF;
  IF purchase.status <> 'payment_pending' THEN
    RAISE EXCEPTION 'La compra no está pendiente de pago.' USING ERRCODE = '23514';
  END IF;

  SELECT * INTO selected_pin FROM pines
  WHERE paquete_id = purchase.package_id AND estado = 'disponible'
  ORDER BY id
  LIMIT 1
  FOR UPDATE SKIP LOCKED;

  IF NOT FOUND THEN
    UPDATE freefire_orders
    SET status = 'out_of_stock_pending_refund',
        fulfillment_status = 'out_of_stock_pending_refund',
        payment_id = p_payment_id,
        paid_at = p_paid_at
    WHERE id = purchase.id
    RETURNING * INTO purchase;
    RETURN jsonb_build_object(
      'status', 'out_of_stock_pending_refund', 'order', to_jsonb(purchase), 'pin', NULL
    );
  END IF;

  UPDATE pines SET estado = 'vendido', order_id = purchase.id, fecha_venta = p_paid_at
  WHERE id = selected_pin.id;
  UPDATE freefire_orders
  SET status = 'paid', fulfillment_status = 'assigned',
      payment_id = p_payment_id, paid_at = p_paid_at
  WHERE id = purchase.id
  RETURNING * INTO purchase;
  RETURN jsonb_build_object(
    'status', 'assigned', 'order', to_jsonb(purchase), 'pin', to_jsonb(selected_pin)
  );
END;
$$;

